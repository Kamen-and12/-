a = float(input("Ежемесячная стипендия = "))
b = float(input("Расходы на проживание (1-й месяц) = "))
t = 0
c = b
m = 10
for m in range(1,m+1):
    t += c
    c *= 1.03
s = a * m
p = t - s
print(f"Общие расходы за {m} месяцев = {t: .2f} рублей")
print(f"Всего получено стипендии = {s: .2f} рублей")
print(f"Деньги у родителей = {p: .2f} рублей")